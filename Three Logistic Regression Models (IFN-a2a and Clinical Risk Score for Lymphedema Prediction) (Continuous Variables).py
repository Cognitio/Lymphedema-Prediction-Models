import pandas as pd
import numpy as np
from sklearn.linear_model import LogisticRegression
from sklearn.metrics import confusion_matrix, roc_auc_score, brier_score_loss, accuracy_score
from sklearn.utils import resample
from sklearn.preprocessing import StandardScaler # Added for scaling
import warnings
from sklearn.exceptions import ConvergenceWarning

# Suppress warnings for cleaner output
warnings.filterwarnings("ignore", category=ConvergenceWarning)
warnings.filterwarnings("ignore", category=UserWarning) # For nan in percentile

def get_performance_metrics(X, y):
    """
    Fits a balanced logistic regression model and returns a dictionary of 7 key metrics.
    Returns a dictionary of NaNs if model fails or data is invalid.
    """
    metrics = {
        'Sensitivity': np.nan, 'Specificity': np.nan, 'Accuracy': np.nan,
        'PPV': np.nan, 'NPV': np.nan, 'AUC': np.nan, 'Brier': np.nan
    }

    # Check if y has both classes
    if len(np.unique(y)) < 2:
        return metrics

    try:
        model = LogisticRegression(max_iter=1000, random_state=42, class_weight='balanced')

        # Handle 1D X array
        X_model = X.copy()
        if X_model.ndim == 1:
            X_model = X_model.values.reshape(-1, 1)

        model.fit(X_model, y)
        y_pred = model.predict(X_model)
        y_pred_proba = model.predict_proba(X_model)[:, 1]

        # Calculate confusion matrix
        tn, fp, fn, tp = confusion_matrix(y, y_pred, labels=[0, 1]).ravel()

        # Calculate metrics, handling division by zero
        metrics['Sensitivity'] = tp / (tp + fn) if (tp + fn) > 0 else np.nan
        metrics['Specificity'] = tn / (tn + fp) if (tn + fp) > 0 else np.nan
        metrics['Accuracy'] = (tp + tn) / (tp + tn + fp + fn)
        metrics['PPV'] = tp / (tp + fp) if (tp + fp) > 0 else np.nan
        metrics['NPV'] = tn / (tn + fn) if (tn + fn) > 0 else np.nan
        metrics['AUC'] = roc_auc_score(y, y_pred_proba)
        metrics['Brier'] = brier_score_loss(y, y_pred_proba)

        return metrics

    except Exception:
        # Catch any other errors during model fitting or evaluation
        return metrics

# --- 1. Load and Prepare Data ---
try:
    # Use the continuous scores file
    file_path = "Modelling with Clinical Risk Scores.xlsx - Continuous Scores.csv"
    df = pd.read_csv(file_path)

    # Rename continuous columns
    col_rename_map = {
        "Lymphedema Equation Score (Clinical Risk)": "Clinical_Score_Continuous",
        "IFN__2a Level": "IFN_Level_Continuous",
        "Lymphedema Presence (1 = lymphedema, 0 = no lymphedema)": "Lymphedema"
    }
    df = df.rename(columns=col_rename_map)

    # Define key columns
    key_cols = ['Clinical_Score_Continuous', 'IFN_Level_Continuous', 'Lymphedema']
    df.dropna(subset=key_cols, inplace=True)

    print(f"Data loaded. N = {len(df)}")
    print(f"Outcome breakdown: {(df['Lymphedema'] == 1).sum()} Lymphedema vs. {(df['Lymphedema'] == 0).sum()} No Lymphedema.")

    # --- NEW STEP: Scale Continuous Predictors ---
    scaler = StandardScaler()
    df[['Clinical_Score_Continuous', 'IFN_Level_Continuous']] = scaler.fit_transform(
        df[['Clinical_Score_Continuous', 'IFN_Level_Continuous']]
    )
    print("Continuous predictors have been standardized (z-score transformed).")

    # Define full data variables using scaled data
    y = df['Lymphedema']
    X_A = df[['Clinical_Score_Continuous']]
    X_B = df[['IFN_Level_Continuous']]
    X_C = df[['Clinical_Score_Continuous', 'IFN_Level_Continuous']]

    # --- 2. Calculate Point Estimates (from full dataset) ---
    print("Calculating point estimates...")
    point_estimates_A = get_performance_metrics(X_A, y)
    point_estimates_B = get_performance_metrics(X_B, y)
    point_estimates_C = get_performance_metrics(X_C, y)

    model_points = {
        'Model A': point_estimates_A,
        'Model B': point_estimates_B,
        'Model C': point_estimates_C
    }

    # --- 3. Run Bootstrap ---
    n_iterations = 1000
    bootstrap_results_A = []
    bootstrap_results_B = []
    bootstrap_results_C = []

    print(f"Starting {n_iterations} bootstrap iterations...")

    valid_iterations = 0
    for i in range(n_iterations):
        # Resample the (already scaled) data with replacement
        df_resampled = resample(df, n_samples=len(df), random_state=i)

        y_r = df_resampled['Lymphedema']

        # Critical check: skip if resampled data has only one class
        if len(np.unique(y_r)) < 2:
            continue

        X_A_r = df_resampled[['Clinical_Score_Continuous']]
        X_B_r = df_resampled[['IFN_Level_Continuous']]
        X_C_r = df_resampled[['Clinical_Score_Continuous', 'IFN_Level_Continuous']]

        # Get metrics for this resampled dataset
        bootstrap_results_A.append(get_performance_metrics(X_A_r, y_r))
        bootstrap_results_B.append(get_performance_metrics(X_B_r, y_r))
        bootstrap_results_C.append(get_performance_metrics(X_C_r, y_r))
        valid_iterations += 1

    print(f"Completed {valid_iterations} valid bootstrap iterations.")

    # --- 4. Calculate 95% Confidence Intervals ---
    metric_names = ['Sensitivity', 'Specificity', 'Accuracy', 'PPV', 'NPV', 'AUC', 'Brier']

    def calculate_cis(bootstrap_results, metric_names):
        """Calculates 2.5th and 97.5th percentiles for each metric."""
        cis = {}
        for metric in metric_names:
            # Get all non-NaN values for this metric from the bootstrap runs
            values = [r[metric] for r in bootstrap_results if r and not np.isnan(r[metric])]

            if len(values) > 0:
                lower = np.percentile(values, 2.5)
                upper = np.percentile(values, 97.5)
                cis[metric] = (lower, upper)
            else:
                cis[metric] = (np.nan, np.nan)
        return cis

    print("Calculating confidence intervals...")
    cis_A = calculate_cis(bootstrap_results_A, metric_names)
    cis_B = calculate_cis(bootstrap_results_B, metric_names)
    cis_C = calculate_cis(bootstrap_results_C, metric_names)

    model_cis = {'Model A': cis_A, 'Model B': cis_B, 'Model C': cis_C}

    # --- 5. Format the Final Table ---

    def format_metric(point_val, ci_tuple):
        """Formats metric as 'Point (CI_Lower - CI_Upper)'."""
        if np.isnan(point_val) or np.isnan(ci_tuple[0]) or np.isnan(ci_tuple[1]):
            return "N/A"
        return f"{point_val:.3f} ({ci_tuple[0]:.3f} - {ci_tuple[1]:.3f})"

    table_data = []
    model_names_map = {
        'Model A': 'Model A: Clinical Risk Only',
        'Model B': 'Model B: IFN-α2A Only',
        'Model C': 'Model C: Combined'
    }

    for model_key, model_name in model_names_map.items():
        row = {'Model Performance Measures': model_name}
        points = model_points[model_key]
        cis = model_cis[model_key]

        row['Sensitivity'] = format_metric(points['Sensitivity'], cis['Sensitivity'])
        row['Specificity'] = format_metric(points['Specificity'], cis['Specificity'])
        row['Accuracy'] = format_metric(points['Accuracy'], cis['Accuracy'])
        row['PPV'] = format_metric(points['PPV'], cis['PPV'])
        row['NPV'] = format_metric(points['NPV'], cis['NPV'])
        row['AUC ROC'] = format_metric(points['AUC'], cis['AUC'])
        row['Brier Score'] = format_metric(points['Brier'], cis['Brier'])

        table_data.append(row)

    # Convert to DataFrame for nice printing
    results_df = pd.DataFrame(table_data)

    print("\n--- Final Results Table (Continuous Data) ---")
    print("Metrics are reported as Point_Estimate (95% CI_Lower - 95% CI_Upper)")
    print(results_df.to_markdown(index=False))

except FileNotFoundError:
    print(f"Error: The file '{file_path}' was not found. Please ensure it is uploaded.")
except Exception as e:
    print(f"An error occurred: {e}")
